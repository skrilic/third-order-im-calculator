#!/usr/bin/env node
/**
 * Turns the hand-maintained starter data into the module the application ships.
 *
 *   data_raw/seed_sites.geojson  ->  src/data/seedSites.js
 *
 * The source file is edited by hand and is the seed's single source of truth;
 * it is deliberately independent of data_raw/transmitters.geojson, so
 * refreshing the full regulator export never silently rewrites the starter set.
 *
 * Validation is not reimplemented here: the file is checked with the very same
 * validateGeoImport() the application uses on a user-supplied file, so a seed
 * that would be rejected on import can never reach the bundle. Nothing is
 * written when validation fails.
 *
 * Usage:
 *   npm run build:seed
 *   node scripts/build-seed-data.mjs [input.geojson] [output.js]
 */

import { readFileSync, writeFileSync } from "node:fs";
import { validateGeoImport } from "../src/domain/geoImport.js";

const inputPath = process.argv[2] ?? "data_raw/seed_sites.geojson";
const outputPath = process.argv[3] ?? "src/data/seedSites.js";

function fail(message) {
  process.stderr.write(`${message}\n`);
  process.exit(1);
}

let document;

try {
  document = JSON.parse(readFileSync(inputPath, "utf8"));
} catch (error) {
  fail(`Cannot read ${inputPath}: ${error.message}`);
}

const validation = validateGeoImport(document);

if (!validation.ok) {
  process.stderr.write(
    `${inputPath} does not match the toic-sites import profile ` +
      `(${validation.errors.length} problem(s)). Nothing was written.\n`
  );
  validation.errors.forEach((error) => {
    process.stderr.write(`  - ${error}\n`);
  });
  process.exit(1);
}

const siteCount = document.features.length;
const transmitterCount = document.features.reduce(
  (total, feature) => total + feature.properties.transmitters.length,
  0
);

const module = `/**
 * Starter data shipped with the application.
 *
 * GENERATED by scripts/build-seed-data.mjs from ${inputPath} — do not edit by
 * hand; edit that file and run \`npm run build:seed\`.
 *
 * It is a plain \`toic-sites\` document, so it is validated and imported through
 * the same path as a user-supplied file.
 *
 * ${siteCount} sites, ${transmitterCount} transmitters.
 */

export const seedSites = ${JSON.stringify(document, null, 2)};

export default seedSites;
`;

writeFileSync(outputPath, module);

process.stderr.write(
  `Wrote ${outputPath}: ${siteCount} sites, ${transmitterCount} transmitters ` +
    `(${document.features.map((f) => f.properties.siteId).join(", ")}).\n`
);
